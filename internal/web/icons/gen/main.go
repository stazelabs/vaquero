// Command gen writes internal/web/icons/ui_gen.go from ui.json and the
// lucide-static package in node_modules. Run it through `make icons`.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// pathData is the only attribute syntax accepted from the package, so
// nothing but drawing data reaches the page.
var pathData = regexp.MustCompile(`^[MmLlHhVvCcSsQqTtAaZz0-9.,\- ]+$`)

func main() { genUI("internal/web/icons") }

// uiElem matches one Lucide drawing element and its attributes; uiAttr one
// attribute. Only the elements and attributes in uiAllowed reach the page.
var (
	uiElem    = regexp.MustCompile(`<([a-z]+)((?:\s+[a-z0-9-]+="[^"]*")*)\s*/?>`)
	uiAttr    = regexp.MustCompile(`([a-z0-9-]+)="([^"]*)"`)
	uiAllowed = map[string][]string{
		"path":     {"d"},
		"circle":   {"cx", "cy", "r"},
		"ellipse":  {"cx", "cy", "rx", "ry"},
		"rect":     {"x", "y", "width", "height", "rx", "ry"},
		"line":     {"x1", "y1", "x2", "y2"},
		"polyline": {"points"},
		"polygon":  {"points"},
	}
)

// genUI writes ui_gen.go: each ui.json name to its Lucide icon's children.
func genUI(dir string) {
	var m struct {
		Source string            `json:"source"`
		Icons  map[string]string `json:"icons"`
	}
	b, err := os.ReadFile(filepath.Join(dir, "ui.json"))
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(b, &m); err != nil {
		log.Fatal(err)
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by internal/web/icons/gen from ui.json; DO NOT EDIT.\n// Icon data: %s\n\npackage icons\n\n", m.Source)
	out.WriteString("var uiIcons = map[string]string{\n")
	for _, name := range slices.Sorted(maps.Keys(m.Icons)) {
		src := strings.TrimSpace(m.Icons[name])
		svg, err := os.ReadFile(filepath.Join("node_modules/lucide-static/icons", src+".svg"))
		if err != nil {
			log.Fatalf("ui icon %q (%s): %v (run npm install)", name, src, err)
		}
		fmt.Fprintf(&out, "\t%q: %q,\n", name, uiInner(name, string(svg)))
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "ui_gen.go"), formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

// uiInner rebuilds an icon's drawing elements from the allowlist, refusing
// anything else inside the <svg>.
func uiInner(name, svg string) string {
	var inner strings.Builder
	for _, e := range uiElem.FindAllStringSubmatch(svg, -1) {
		tag := e[1]
		if tag == "svg" {
			continue
		}
		keep, ok := uiAllowed[tag]
		if !ok {
			log.Fatalf("ui icon %q: element <%s> isn't allowed", name, tag)
		}
		attrs := map[string]string{}
		for _, a := range uiAttr.FindAllStringSubmatch(e[2], -1) {
			if a[1] == "fill" && a[2] == "currentColor" { // a filled dot (tag)
				attrs["fill"] = a[2]
				continue
			}
			if !slices.Contains(keep, a[1]) || !pathData.MatchString(a[2]) {
				log.Fatalf("ui icon %q: <%s %s=%q> isn't allowed", name, tag, a[1], a[2])
			}
			attrs[a[1]] = a[2]
		}
		inner.WriteString("<" + tag)
		for _, k := range append(keep, "fill") {
			if v, ok := attrs[k]; ok {
				fmt.Fprintf(&inner, " %s=%q", k, v)
			}
		}
		inner.WriteString("></" + tag + ">")
	}
	if inner.Len() == 0 {
		log.Fatalf("ui icon %q: nothing to draw", name)
	}
	return inner.String()
}
